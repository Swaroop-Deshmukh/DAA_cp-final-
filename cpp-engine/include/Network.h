#ifndef NETWORK_H
#define NETWORK_H

#include <string>
#include <vector>
#include <iostream>

/**
 * @brief Represents a client geographic region generating CDN traffic.
 * 
 * In a Content Delivery Network (CDN), traffic originates from users situated in
 * various geographical regions. Each region aggregates user requests that need
 * to be routed to suitable edge servers.
 */
struct Region {
    std::string name;       // Name of the geographic region (e.g., "Pune", "Mumbai")
    double trafficDemand;   // Traffic demand generated by this region in requests per second (req/s)

    // Constructor for easy initialization
    Region(const std::string& regionName, double demand);
};

/**
 * @brief Represents an edge CDN server capable of handling user traffic.
 * 
 * An edge server is deployed close to users to serve content with low latency.
 * Each server has a configured physical capacity, an active operational status,
 * and an effective available capacity that drops to zero upon server failure.
 */
struct Server {
    std::string name;               // Name of the server (e.g., "Pune Server")
    double maxCapacity;             // Configured capacity in req/s (preserved across outages)
    double configuredCapacity;      // Original configured capacity (req/s)
    double availableCapacity;       // Available capacity for routing: 0 when inactive, configuredCapacity when active
    bool isActive;                  // Operational status: true if online, false if failed/offline

    // Constructor with default active status set to true
    Server(const std::string& serverName, double capacity, bool active = true);

    // Operational state mutators
    void fail();
    void recover();
};

/**
 * @brief Represents a network link connecting a client region to an edge server.
 * 
 * Each link has a physical base latency (due to fiber distance and network hops),
 * an added congestion latency induced by transient bottlenecks, and a unit bandwidth cost.
 */
struct NetworkLink {
    std::string regionName;         // Originating client region
    std::string serverName;         // Target edge server
    double baseLatencyMs;           // Base network latency in milliseconds
    double congestionLatencyMs;     // Additional latency caused by network congestion
    double bandwidthCost;           // Cost per unit of bandwidth (e.g., $/Gbps)
    double bandwidthCapacity;       // Maximum bandwidth throughput limit on this link (req/s)
    double cacheHitRatio;          // Effective cache hit ratio on this connection [0.0, 1.0]

    NetworkLink(const std::string& reg, const std::string& srv, double baseLatency, 
                double cost = 1.0, double bwCapacity = 4000.0, double hitRatio = 0.80);

    // Returns total effective latency including congestion
    double getEffectiveLatency() const;
};

/**
 * @brief Manages the overall CDN network topology, containing client regions, edge servers, and links.
 * 
 * The Network class acts as the central container for all CDN components. It provides
 * safe insertion methods with input validation, lookups, and formatted display functions.
 */
class Network {
private:
    std::vector<Region> regions;        // List of all registered user regions
    std::vector<Server> servers;        // List of all registered CDN edge servers
    std::vector<NetworkLink> links;     // Interconnecting links between regions and servers

public:
    Network() = default;

    /**
     * @brief Adds a new user region to the network.
     * @param regionName Name of the region (must not be empty).
     * @param trafficDemand Traffic generated in req/s (must be non-negative).
     * @return true if added successfully, false if validation fails.
     */
    bool addRegion(const std::string& regionName, double trafficDemand);

    /**
     * @brief Adds a new edge server to the network.
     * @param serverName Name of the server (must not be empty).
     * @param maxCapacity Maximum request processing capacity in req/s (must be positive).
     * @param isActive Initial operational status (defaults to true).
     * @return true if added successfully, false if validation fails.
     */
    bool addServer(const std::string& serverName, double maxCapacity, bool isActive = true);

    /**
     * @brief Adds a network link between a region and a server.
     * @param regionName Source region name (must exist).
     * @param serverName Destination server name (must exist).
     * @param baseLatencyMs Base latency in ms (must be non-negative).
     * @param bandwidthCost Unit bandwidth cost (must be non-negative).
     * @param bandwidthCapacity Bandwidth capacity limit in req/s (must be positive).
     * @param cacheHitRatio Expected cache hit ratio [0.0, 1.0].
     * @return true if added successfully, false if validation fails.
     */
    bool addLink(const std::string& regionName, const std::string& serverName, 
                 double baseLatencyMs, double bandwidthCost = 1.0,
                 double bandwidthCapacity = 4000.0, double cacheHitRatio = 0.80);

    // Direct mutators and finders
    bool setRegionDemand(const std::string& regionName, double newDemand);
    Region* getRegion(const std::string& regionName);
    const Region* getRegion(const std::string& regionName) const;

    Server* getServer(const std::string& serverName);
    const Server* getServer(const std::string& serverName) const;

    NetworkLink* getLink(const std::string& regionName, const std::string& serverName);
    const NetworkLink* getLink(const std::string& regionName, const std::string& serverName) const;

    // Display functions
    void displayRegions() const;
    void displayServers() const;
    void displayLinks() const;
    void displayNetwork() const;

    // Getters for inspecting network state
    const std::vector<Region>& getRegions() const;
    std::vector<Region>& getRegions();

    const std::vector<Server>& getServers() const;
    std::vector<Server>& getServers();

    const std::vector<NetworkLink>& getLinks() const;
    std::vector<NetworkLink>& getLinks();

    // Summary calculations
    double getTotalTrafficDemand() const;
    double getTotalActiveServerCapacity() const;
    double getTotalConfiguredServerCapacity() const;
};

#endif // NETWORK_H
